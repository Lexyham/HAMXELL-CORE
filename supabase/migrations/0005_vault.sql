-- HAMXELL CORE, Phase 6: credentials vault. Run after 0004.
-- Secrets are stored only as AES-256-GCM ciphertext (see lib/vault/crypto.ts). Owner role only.
create function public.is_owner() returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admins where user_id = auth.uid() and role = 'owner')
$$;

-- Non-secret operational facts per project (hosting, DB provider, env var NAMES, API key REFERENCES, recovery steps).
create table public.project_infra (
  project_id uuid primary key references public.projects (id) on delete cascade,
  admin_url text,
  username text,
  hosting text,
  db_provider text,
  deploy_platform text,
  env_var_names text[] not null default '{}',
  api_key_refs text[] not null default '{}',
  config_notes text not null default '',
  recovery_steps text not null default '',
  updated_at timestamptz not null default now()
);

create table public.vault_entries (
  id uuid primary key,                       -- generated by the app; also used as the GCM additional authenticated data
  project_id uuid not null references public.projects (id) on delete cascade,
  label text not null check (char_length(label) between 1 and 100),
  kind text not null default 'password' check (kind in ('password', 'api_key', 'token', 'certificate', 'other')),
  ciphertext text not null,
  iv text not null,
  tag text not null,
  key_version int not null default 1,
  created_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_revealed_at timestamptz
);
create index vault_entries_project_idx on public.vault_entries (project_id);

create trigger project_infra_updated_at before update on public.project_infra for each row execute function public.set_updated_at();
create trigger vault_entries_updated_at before update on public.vault_entries for each row execute function public.set_updated_at();

alter table public.project_infra enable row level security;
alter table public.vault_entries enable row level security;
create policy infra_owner_all on public.project_infra for all using (public.is_owner()) with check (public.is_owner());
create policy vault_owner_all on public.vault_entries for all using (public.is_owner()) with check (public.is_owner());
